
import { describe, expect, it } from "vitest";
import {
  createMissingNumberChallenge,
  selectMissingNumberAnswer,
  finishMissingNumberFeedback,
} from "../src/game/missingNumberEngine";
import { generateMissingNumberPuzzle } from "../src/game/missingNumber";
import type { MissingNumberPuzzle } from "../src/game/missingNumber";
import type { DifficultyConfig } from "../src/game/difficulty";

const difficulty: DifficultyConfig = {
  minNumber: 1,
  maxNumber: 10,
  operations: ["+", "−"],
};

function makePuzzle(answer: number): MissingNumberPuzzle {
  return {
    id: `puzzle-${answer}`,
    text: `5 + ? = ${5 + answer}`,
    answer,
    options: [answer, answer + 1, answer + 2],
  };
}

describe("Missing Number challenge engine", () => {
  it("starts with the configured rounds and lives", () => {
    const state = createMissingNumberChallenge(makePuzzle(3), 5, 3);

    expect(state.status).toBe("playing");
    expect(state.roundIndex).toBe(0);
    expect(state.totalRounds).toBe(5);
    expect(state.lives).toBe(3);
  });

  it("advances to the next puzzle after a correct answer", () => {
    const first = makePuzzle(3);
    const next = makePuzzle(4);
    const state = createMissingNumberChallenge(first, 5, 3);

    const updated = selectMissingNumberAnswer(state, 3, next);

    expect(updated.roundIndex).toBe(1);
    expect(updated.puzzle).toBe(next);
    expect(updated.lives).toBe(3);
    expect(updated.status).toBe("playing");
  });

  it("loses one life after an incorrect answer", () => {
    const state = createMissingNumberChallenge(makePuzzle(3));

    const updated = selectMissingNumberAnswer(state, 4);

    expect(updated.lives).toBe(2);
    expect(updated.status).toBe("feedback");
  });

  it("returns to playing after wrong-answer feedback", () => {
    const state = createMissingNumberChallenge(makePuzzle(3));
    const wrongAnswer = selectMissingNumberAnswer(state, 4);

    const updated = finishMissingNumberFeedback(wrongAnswer);

    expect(updated.status).toBe("playing");
    expect(updated.lives).toBe(2);
  });

  it("fails when the last life is lost", () => {
    let state = createMissingNumberChallenge(makePuzzle(3), 5, 1);

    state = selectMissingNumberAnswer(state, 4);

    expect(state.status).toBe("failed");
    expect(state.lives).toBe(0);
  });

  it("wins after the final correct answer", () => {
    const state = createMissingNumberChallenge(makePuzzle(3), 1, 3);

    const updated = selectMissingNumberAnswer(state, 3);

    expect(updated.status).toBe("success");
    expect(updated.roundIndex).toBe(1);
  });

  it("ignores answers that are not among the options", () => {
    const state = createMissingNumberChallenge(makePuzzle(3));

    const updated = selectMissingNumberAnswer(state, 99);

    expect(updated).toBe(state);
  });

  it("rejects invalid round and life counts", () => {
    expect(() =>
      createMissingNumberChallenge(makePuzzle(3), 0, 3),
    ).toThrow();

    expect(() =>
      createMissingNumberChallenge(makePuzzle(3), 5, 0),
    ).toThrow();
  });

  it("works with puzzles generated by the real generator", () => {
    const puzzle = generateMissingNumberPuzzle(difficulty);
    const state = createMissingNumberChallenge(puzzle);

    expect(state.puzzle.options).toContain(state.puzzle.answer);
    expect(state.puzzle.options).toHaveLength(3);
  });
});
